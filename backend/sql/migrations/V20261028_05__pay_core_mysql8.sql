-- AgenticCPS V20261028_05: 14 pay Java DO tables, MySQL 8.
-- This is an additive schema candidate derived from model fields; no test fixtures copied.
-- For sealed test environments only until Mapper, service & end-to-end scenarios pass.
-- All real payment gateways, settlements, withdrawals and refunds stay disabled.
-- MySQL tables created empty. No financial seed data, no payment credentials.

-- WARNING: pay_wallet and pay_wallet_transaction are NOT the CPS rebate ledger.
-- Wallet transaction business-key uniqueness is a proposed idempotency guard requiring further review.

